/** Los dos fotogramas de un ejercicio; [] si no hay medios asociados. */
export function mediaFrames(exerciseId: string): string[] {
  const folder = MEDIA_FOLDER[exerciseId];
  if (!folder) return [];
  const encoded = encodeURIComponent(folder);
  return [`${BASE}/${encoded}/0.jpg`, `${BASE}/${encoded}/1.jpg`];
}

